function writeMcpDiscovery(port, userDataPath) {
  try {
    const discoveryPath = path.join(userDataPath, "mcp_discovery.json");
    const tokenPath = path.join(userDataPath, "mcp_token");
    let token = "";
    if (fs.existsSync(tokenPath)) {
      token = fs.readFileSync(tokenPath, "utf8").trim();
    }
    if (!token) {
      token = crypto.randomBytes(32).toString("base64url");
      fs.writeFileSync(tokenPath, token, { mode: 0o600 });
    }
    fs.writeFileSync(
      discoveryPath,
      JSON.stringify(
        {
          host: "127.0.0.1",
          port: Number(port),
          base_url: `http://127.0.0.1:${port}/api`,
          token,
          discovery_path: discoveryPath,
        },
        null,
        2,
      ),
      { mode: 0o600 },
    );
    log.info(`MCP discovery written to ${discoveryPath}`);
  } catch (error) {
    log.warn(`Could not write MCP discovery file: ${error}`);
  }
}

function shellQuote(value) {
  return `'${String(value).replace(/'/g, `'\\''`)}'`;
}

function writeMcpLauncher(userDataPath) {
  // AppImage mounts under /tmp/.mount_* are ephemeral. Claude Desktop keeps the
  // mcpServers.command path across restarts, so point it at a stable launcher that
  // remounts the AppImage (via APPIMAGE) before running `resources/backend/api mcp`.
  try {
    const appImage = process.env.APPIMAGE;
    if (!appImage || !fs.existsSync(appImage)) {
      return;
    }
    if (!String(backendPath).includes("/tmp/.mount_")) {
      return;
    }
    const launcherPath = path.join(userDataPath, "run-mcp");
    const script = `#!/usr/bin/env bash
# Auto-generated by Research Marker for Claude Desktop / Cowork MCP.
# Do not edit — reopen Research Marker to refresh after moving the AppImage.
set -euo pipefail
APPIMAGE=${shellQuote(appImage)}
BACKEND_REL='resources/backend/api'
if [[ ! -f "$APPIMAGE" ]]; then
  echo "Research Marker AppImage not found: $APPIMAGE" >&2
  echo "Open Research Marker once to refresh the MCP launcher, then restart Claude Desktop." >&2
  exit 1
fi
if [[ ! -x "$APPIMAGE" ]]; then
  chmod +x "$APPIMAGE" 2>/dev/null || true
fi
MOUNT_LOG="$(mktemp)"
cleanup() {
  if [[ -n "\${MOUNT_PID:-}" ]]; then
    kill "$MOUNT_PID" 2>/dev/null || true
    wait "$MOUNT_PID" 2>/dev/null || true
  fi
  rm -f "$MOUNT_LOG"
}
trap cleanup EXIT
"$APPIMAGE" --appimage-mount >"$MOUNT_LOG" &
MOUNT_PID=$!
MOUNT_POINT=""
for _ in $(seq 1 100); do
  if [[ -s "$MOUNT_LOG" ]]; then
    MOUNT_POINT="$(head -n 1 "$MOUNT_LOG")"
    break
  fi
  if ! kill -0 "$MOUNT_PID" 2>/dev/null; then
    break
  fi
  sleep 0.05
done
if [[ -z "$MOUNT_POINT" || ! -x "$MOUNT_POINT/$BACKEND_REL" ]]; then
  echo "Failed to mount Research Marker AppImage for MCP." >&2
  echo "Open Research Marker, then restart Claude Desktop." >&2
  exit 1
fi
"$MOUNT_POINT/$BACKEND_REL" mcp "$@"
`;
    fs.writeFileSync(launcherPath, script, { mode: 0o755 });
    log.info(`MCP launcher written to ${launcherPath}`);
  } catch (error) {
    log.warn(`Could not write MCP launcher: ${error}`);
  }
}

