ipcMain.handle("sidebar:pop-out", (event, payload = {}) => {
  if (!mainWindow || event.sender.id !== mainWindow.webContents.id) {
    return { ok: false, reason: "Only the main viewer can open the sidebar." };
  }

  const documentId = String(payload.documentId ?? "");
  if (!/^\d+$/.test(documentId)) {
    return { ok: false, reason: "Invalid document id." };
  }

  if (sidebarWindow && !sidebarWindow.isDestroyed()) {
    sidebarWindow.show();
    sidebarWindow.focus();
    return { ok: true, alreadyOpen: true };
  }

  createSidebarWindow(documentId);
  return { ok: true, alreadyOpen: false };
});

ipcMain.handle("sidebar:focus-popout", (event) => {
  if (!mainWindow || event.sender.id !== mainWindow.webContents.id) {
    return { ok: false };
  }
  if (!sidebarWindow || sidebarWindow.isDestroyed()) {
    return { ok: false };
  }
  sidebarWindow.show();
  sidebarWindow.focus();
  return { ok: true };
});

ipcMain.handle("sidebar:close-popout", (event) => {
  if (!sidebarWindow || sidebarWindow.isDestroyed()) {
    return { ok: false };
  }
  const isSidebarSender = event.sender.id === sidebarWindow.webContents.id;
  const isMainSender =
    mainWindow &&
    !mainWindow.isDestroyed() &&
    event.sender.id === mainWindow.webContents.id;
  if (!isSidebarSender && !isMainSender) {
    return { ok: false };
  }
  sidebarWindow.close();
  return { ok: true };
});

ipcMain.on("sidebar:reveal-annotation", (event, payload = {}) => {
  if (
    !sidebarWindow ||
    sidebarWindow.isDestroyed() ||
    event.sender.id !== sidebarWindow.webContents.id ||
    String(payload.documentId ?? "") !== sidebarDocumentId
  ) {
    return;
  }
  if (mainWindow && !mainWindow.isDestroyed()) {
    mainWindow.webContents.send("sidebar:reveal-annotation", payload);
    mainWindow.show();
  }
});

ipcMain.on("splash:progress", (event, payload = {}) => {
  if (
    !mainWindow ||
    mainWindow.isDestroyed() ||
    event.sender.id !== mainWindow.webContents.id
  ) {
    log.warn("[Startup] Ignoring splash progress from an unexpected renderer");
    return;
  }
  const percent = Number(payload.percent);
  const message = payload.message;
  if (!Number.isFinite(percent)) {
    log.warn("[Startup] Ignoring non-numeric splash progress from renderer");
    return;
  }
  log.info(
    `[Startup] Renderer progress IPC: ${Math.round(percent)}% ${message || ""}`,
  );
  setSplashProgress(percent, message);
});

